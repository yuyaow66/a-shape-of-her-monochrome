export function mountFollowupInterviews(){
 const mom=document.getElementById('mom');
 const panelSelector='[data-name="Interview — editable questions and answers"]';
 const template=mom.querySelector('[data-name^="Question"]').cloneNode(true);
 const strip=node=>{node.removeAttribute('data-node-id');for(const child of node.querySelectorAll('[data-node-id]'))child.removeAttribute('data-node-id');};
 const addAnswers=(panel,person,offset)=>{
  person.answers.forEach((answer,index)=>{
   const block=template.cloneNode(true);strip(block);block.dataset.name=`Question ${offset+index+1}`;
   block.firstElementChild.textContent=followupQuestions[index].heading;
   const body=block.children[1],paragraph=body.querySelector('p').cloneNode(false);
   body.replaceChildren(...answer.paragraphs.map(value=>{const row=paragraph.cloneNode(false);row.textContent=value;return row;}));
   panel.append(block);
  });
 };
 for(const [key,person]of Object.entries(followupPeople)){
  if(key==='mom')continue;
  const screen=mom.cloneNode(true);screen.id=key;strip(screen);screen.classList.add('additional-interview');
  screen.firstElementChild.dataset.name=`Interview — ${person.name}`;
  const panel=screen.querySelector(panelSelector);panel.replaceChildren();addAnswers(panel,person,0);
  const photos=screen.querySelector('[data-name="Family photographs — original proportions"]');photos.replaceChildren();
  if(person.photos){
   for(const [index,src] of person.photos.entries()){
    const frame=document.createElement('div');frame.className='interview-photo-frame';
    const image=document.createElement('img');image.src=src;image.alt=`${person.name}, ${index===0?'earlier photograph':'recent photograph'}`;image.loading='lazy';frame.append(image);photos.append(frame);
   }
  }else{
  const placeholder=document.createElement('div');placeholder.className='interview-photo-placeholder';
  const name=document.createElement('p');name.textContent=person.name;
  const label=document.createElement('p');label.textContent='PHOTOGRAPH TO COME';placeholder.append(name,label);photos.append(placeholder);
  }
  mom.parentElement.append(screen);
 }
 addAnswers(mom.querySelector(panelSelector),followupPeople.mom,4);
 for(const key of Object.keys(interviewPeople)){
  const nav=document.getElementById(key).querySelector('[data-name="Interview navigation — left tabs"]');
  const tabTemplate=nav.querySelector('a').cloneNode(true);
  for(const [id,person]of Object.entries(followupPeople)){
   if(id==='mom')continue;
   const link=tabTemplate.cloneNode(true);strip(link);link.dataset.name=person.name;link.href=`#${id}`;link.querySelector('p').textContent=person.name;
   nav.append(link);
  }
 }
}
