export function mountBookStudies(){
 const root=document.getElementById('film');
 const nav=root.querySelector('[data-name="Interview navigation — left tabs"]');
 const photos=root.querySelector('[data-name="Family photographs — original proportions"]');
 const studies=root.querySelector('[data-name="Interview — editable questions and answers"]');
 const template=studies.firstElementChild;
 const reality=studies.lastElementChild;
 const realityImage=photos.lastElementChild;
 const realityTab=nav.lastElementChild;
 for(const [index,book] of books.entries()){
  const block=template.cloneNode(true);
  block.querySelectorAll('[data-node-id]').forEach(node=>node.removeAttribute('data-node-id'));
  block.removeAttribute('data-node-id');
  block.dataset.name=`Question ${index+4}`;
  block.classList.add('book-study');
  const heading=block.firstElementChild;
  heading.replaceChildren();
  const title=document.createElement('p');title.textContent=book.title;heading.append(title);
  const body=block.children[1];body.replaceChildren();
  const meta=document.createElement('p');meta.className='film-meta';
  for(const text of [book.year,book.author]){
   const chip=document.createElement('span');chip.className='film-meta-chip';chip.textContent=text;meta.append(chip);
  }
  body.append(meta);
  if(book.subtitle){const subtitle=document.createElement('p');subtitle.textContent=book.subtitle;body.append(subtitle);}
  if(book.quote){
   const quote=document.createElement('blockquote');quote.className='book-quote';
   const mark=document.createElement('span');mark.textContent=`“${book.quote}”`;quote.append(mark);body.append(quote);
  }
  for(const text of book.paragraphs){const paragraph=document.createElement('p');paragraph.textContent=text;body.append(paragraph);}
  const citation=document.createElement('p');citation.className='book-citation';citation.textContent=book.citation;
  const source=document.createElement('a');source.href=book.source;source.target='_blank';source.rel='noopener noreferrer';source.textContent=book.sourceLabel+' ↗';source.className='book-source';
  body.append(citation,source);
  for(const link of block.querySelectorAll('.movie-link-coming-soon'))link.remove();
  studies.append(block);
  const plate=document.createElement('div');plate.className='book-cover';
  const image=document.createElement('img');image.src=book.cover;image.alt=`${book.title} by ${book.author} — book cover`;image.decoding='async';
  const credit=document.createElement('a');credit.className='book-cover-credit';credit.href=book.coverSource;credit.target='_blank';credit.rel='noopener noreferrer';credit.textContent=`Cover: ${book.coverCredit}`;
  plate.append(image,credit);photos.append(plate);
  const tab=nav.firstElementChild.cloneNode(true);tab.removeAttribute('aria-current');tab.removeAttribute('data-node-id');
  tab.querySelectorAll('[data-node-id]').forEach(node=>node.removeAttribute('data-node-id'));
  tab.querySelector('p').textContent=book.title;
  tab.addEventListener('click',()=>{
   location.hash=`film/${index+3}`;
   requestAnimationFrame(()=>{root.querySelector('[data-name="Films — scrollable studies"]').scrollTop=block.offsetTop;});
  });
  nav.append(tab);
 }
 const realityHeader=document.createElement('header');realityHeader.className='reality-header';
 const realityTitle=document.createElement('h2');realityTitle.className='reality-title';
 const titleContext=document.createElement('span');titleContext.textContent='Connecting the films & books with ';
 const titleReality=document.createElement('strong');titleReality.textContent='REALITY';
 realityTitle.append(titleContext,titleReality);
 const intro=document.createElement('p');intro.className='reality-intro';intro.textContent='These films and books make me think of my own family.';
 realityHeader.append(realityTitle,intro);
 const realityBody=document.createElement('div');realityBody.className='reality-reading';
 const directory=document.createElement('nav');directory.className='reality-directory';directory.setAttribute('aria-label','Personal reflections by work');
 const reflections=document.createElement('div');reflections.className='reality-reflections';
 const noteHeadings=[];
 const noteLinks=[];
 for(const [index,section] of realityConnections.entries()){
  const article=document.createElement('article');article.className='reality-note';
  const heading=document.createElement('h3');heading.id=`reality-note-${index+1}`;heading.className='reality-note-title';heading.textContent=section.title;heading.tabIndex=-1;
  article.setAttribute('aria-labelledby',heading.id);article.append(heading);noteHeadings.push(heading);
  const link=document.createElement('a');link.href='#film/8';
  const number=document.createElement('span');number.className='reality-note-number';number.textContent=String(index+1).padStart(2,'0');number.setAttribute('aria-hidden','true');
  const label=document.createElement('span');label.textContent=section.title;link.append(number,label);
  if(index===0)link.setAttribute('aria-current','location');
  link.addEventListener('click',event=>{
   event.preventDefault();
   const scroller=root.querySelector('[data-name="Films — scrollable studies"]');
   const frame=scroller.getBoundingClientRect();
   const scale=frame.height/scroller.clientHeight;
   const top=scroller.scrollTop+(heading.getBoundingClientRect().top-frame.top)/scale-24;
   heading.focus({preventScroll:true});
   scroller.scrollTo({top,behavior:matchMedia('(prefers-reduced-motion: reduce)').matches?'auto':'smooth'});
  });
  directory.append(link);noteLinks.push(link);
  for(const text of section.paragraphs){
   const paragraph=document.createElement('p');paragraph.textContent=text;article.append(paragraph);
  }
  reflections.append(article);
 }
 realityBody.append(directory,reflections);reality.replaceChildren(realityHeader,realityBody);
 const realityScroller=root.querySelector('[data-name="Films — scrollable studies"]');
 let pendingFrame=0;
 const updateDirectory=()=>{
  pendingFrame=0;
  if(root.hidden)return;
  const frame=realityScroller.getBoundingClientRect();
  const threshold=frame.top+frame.height*.25;
  let current=0;
  noteHeadings.forEach((heading,index)=>{if(heading.getBoundingClientRect().top<=threshold)current=index;});
  noteLinks.forEach((link,index)=>{if(index===current)link.setAttribute('aria-current','location');else link.removeAttribute('aria-current');});
 };
 realityScroller.addEventListener('scroll',()=>{if(!pendingFrame)pendingFrame=requestAnimationFrame(updateDirectory);},{passive:true});
 addEventListener('resize',()=>{if(!pendingFrame)pendingFrame=requestAnimationFrame(updateDirectory);});
 studies.append(reality);photos.append(realityImage);nav.append(realityTab);
 for(const group of [photos,studies]){
  [...group.children].forEach((item,index)=>{
   if(group===studies)item.dataset.name=`Question ${index+1}`;
   item.style.setProperty('--study-row',index+1);
   item.style.setProperty('--study-mobile-row',index*2+(group===photos?1:2));
  });
 }
 root.classList.add('book-studies-ready');
}
